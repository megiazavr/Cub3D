#include "../../headers/cub3D.h"

int empty_flag(char *l)
{
	int	i;
	int	empty_l;

	i = 0;
	empty_l = 1;
	while (l[i])
	{
		if (l[i] != ' ' && l[i] != '\t' && l[i] != '\n' && l[i] != '\r')
			empty_l = 0;
		i++;
	}
	if (i > 0 && l[i - 1] == '\n')
		l[i - 1] = '\0';
	return (empty_l);
}